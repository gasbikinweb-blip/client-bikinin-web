export interface ProjectItem {
  id: string;
  src: string;
  thumbSrc: string;
  alt: string;
  productType: string;
  filterCategory: ProjectFilterCategory;
  roomType: string;
  location?: string;
  kind: 'proyek' | 'ilustrasi';
  width: number;
  height: number;
  featured?: boolean;
}

export interface VideoProjectItem {
  id: string;
  title: string;
  description: string;
  src: string;
  poster: string;
  productType: string;
  roomType: string;
  location?: string;
}

function projectPaths(slug: string) {
  return {
    src: `/projects/${slug}.webp`,
    thumbSrc: `/projects/thumbs/${slug}.webp`,
  };
}

